#!/usr/bin/env python3
"""Generate apfs/unicode_tables.h for APFS filename normalization.

APFS hashes directory entry names after canonical decomposition (NFD) and,
on case-insensitive volumes, full case folding of each decomposed character.
This script dumps the three tables that algorithm needs from Python's
unicodedata module:
  - canonical combining classes (ccc != 0), as ranges
  - full canonical decompositions (excluding algorithmic Hangul)
  - full case folding (status C + F)
Run: python3 tools/gen_unicode.py > apfs/unicode_tables.h
"""
import sys
import unicodedata

MAXCP = 0x110000

def full_nfd(cp):
    s = unicodedata.normalize('NFD', chr(cp))
    return [ord(c) for c in s]

def is_hangul_syllable(cp):
    return 0xAC00 <= cp <= 0xD7A3

def main():
    out = sys.stdout
    out.write('/* Generated by tools/gen_unicode.py from Unicode %s. Do not edit. */\n\n'
              % unicodedata.unidata_version)
    out.write('#ifndef APFS_UNICODE_TABLES_H\n#define APFS_UNICODE_TABLES_H\n\n#include <stdint.h>\n\n')

    # Combining classes as ranges of equal non-zero ccc
    ranges = []
    cp = 0
    while cp < MAXCP:
        c = unicodedata.combining(chr(cp))
        if c:
            start = cp
            while cp + 1 < MAXCP and unicodedata.combining(chr(cp + 1)) == c:
                cp += 1
            ranges.append((start, cp, c))
        cp += 1
    out.write('typedef struct { uint32_t first, last; uint8_t ccc; } apfs_ccc_range_t;\n')
    out.write('static const apfs_ccc_range_t apfs_ccc_ranges[] = {\n')
    for a, b, c in ranges:
        out.write('\t{0x%05X, 0x%05X, %d},\n' % (a, b, c))
    out.write('};\n#define APFS_CCC_RANGES %d\n\n' % len(ranges))

    # Decompositions: flat pool + index (cp, offset, length)
    pool = []
    index = []
    for cp in range(MAXCP):
        if is_hangul_syllable(cp) or 0xD800 <= cp <= 0xDFFF:
            continue
        d = full_nfd(cp)
        if d != [cp]:
            index.append((cp, len(pool), len(d)))
            pool.extend(d)
    out.write('typedef struct { uint32_t cp; uint16_t off; uint8_t len; } apfs_map_entry_t;\n')
    out.write('static const uint32_t apfs_nfd_pool[] = {\n')
    for i in range(0, len(pool), 8):
        out.write('\t' + ', '.join('0x%05X' % x for x in pool[i:i + 8]) + ',\n')
    out.write('};\n')
    out.write('static const apfs_map_entry_t apfs_nfd_index[] = {\n')
    for cp, off, ln in index:
        out.write('\t{0x%05X, %d, %d},\n' % (cp, off, ln))
    out.write('};\n#define APFS_NFD_ENTRIES %d\n\n' % len(index))

    # Full case folding
    pool = []
    index = []
    for cp in range(MAXCP):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        f = chr(cp).casefold()
        if f != chr(cp):
            index.append((cp, len(pool), len(f)))
            pool.extend(ord(c) for c in f)
    out.write('static const uint32_t apfs_cf_pool[] = {\n')
    for i in range(0, len(pool), 8):
        out.write('\t' + ', '.join('0x%05X' % x for x in pool[i:i + 8]) + ',\n')
    out.write('};\n')
    out.write('static const apfs_map_entry_t apfs_cf_index[] = {\n')
    for cp, off, ln in index:
        out.write('\t{0x%05X, %d, %d},\n' % (cp, off, ln))
    out.write('};\n#define APFS_CF_ENTRIES %d\n\n' % len(index))
    out.write('#endif\n')

if __name__ == '__main__':
    main()
